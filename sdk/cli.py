#!/usr/bin/env python3
"""
pyrobot-cli — plugin scaffolding for PyRobot Studio.

    python -m sdk.cli create-plugin my_filter --category Processing \\
        --input in:image --output out:image

Generates a ready-to-run plugin file under plugins/user/<name>.py with:
  - a correctly-shaped PluginManifest (id, category, ports, one example param)
  - a Node subclass with on_message stubbed in (for a node with inputs) or
    on_start/on_stop stubbed in (for a source node with no inputs)
  - enough working code that it's immediately discoverable by the backend's
    plugin registry and shows up in the Studio palette without edits —
    the intent is "generate something that runs", not just a doc comment.

This is intentionally a plain argparse script with a template string, not
a separate package — so it has zero extra dependencies beyond the SDK
itself, and works the moment you clone the repo.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

VALID_PORT_TYPES = {"image", "pointcloud", "pose", "imu", "string", "number", "bool", "json", "any"}

